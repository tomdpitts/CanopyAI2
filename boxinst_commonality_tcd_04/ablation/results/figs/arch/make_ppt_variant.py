"""Derive the 'PowerPoint graphics' styling of Fig 1 (Tom 2026-11-05: "show me a copy in a powerpoint graphics style").

lace_architecture.tex -> lace_architecture_ppt.tex by text substitution only, so the copy always carries the paper
figure's content (same insets, same coordinates). Style: white cards with drop shadows on a light slide, solid
colour header bars per stage (detection = trained orange, encoding = frozen blue, box-to-mask = fitted green,
input/output = charcoal), white titles, icons on white badges, thick block arrows.

Run from figs/:  ../../../../.venv/bin/python arch/make_ppt_variant.py && tectonic lace_architecture_ppt.tex
"""
import os

FIGS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC, DST = os.path.join(FIGS, "lace_architecture.tex"), os.path.join(FIGS, "lace_architecture_ppt.tex")
HEAD = {"A": "ink!80", "B": "trn", "C": "frz", "D": "ffit", "E": "ink!80"}
BAR = 0.5   # header bar height, cm


def main():
    s = open(SRC).read()

    def rep(a, b, n=1):
        nonlocal s
        assert s.count(a) == n, (a, s.count(a)); s = s.replace(a, b)

    rep("\\documentclass[tikz,border=3pt]{standalone}",
        "% GENERATED by arch/make_ppt_variant.py from lace_architecture.tex -- edit that file, not this one.\n"
        "\\documentclass[tikz,border=0pt]{standalone}")
    rep("\\begin{document}", r"""\usetikzlibrary{shadows}
\definecolor{slide}{HTML}{EDF0F4}
\tikzset{
  panel/.style={draw=ink!8, fill=white, rounded corners=7pt, line width=0.4pt,
                drop shadow={shadow xshift=1.6pt, shadow yshift=-1.6pt, opacity=0.22, fill=ink}},
  title/.style={font=\normalsize\bfseries, text=white},
  arr/.style={-{Triangle[length=6pt,width=8pt]}, line width=1.8pt, ink!40, rounded corners=4pt},
  sarr/.style={-{Triangle[length=5pt,width=6.5pt]}, line width=1.4pt, ink!30},
  img/.style={inner sep=0pt, draw=white, line width=1.5pt,
              drop shadow={shadow xshift=0.8pt, shadow yshift=-0.8pt, opacity=0.25, fill=ink}},
}
\begin{document}""")
    rep("\\pgfmathsetmacro{\\zmax}{max(\\zoomnx,\\zoomny)}\n",
        "\\pgfmathsetmacro{\\zmax}{max(\\zoomnx,\\zoomny)}\n\\fill[slide] (-0.45,0.75) rectangle (18.35,-7.7);\n")
    bars = "".join(
        f"\\begin{{scope}}\\clip[rounded corners=7pt] (P{n}.south west) rectangle (P{n}.north east);"
        f"\\fill[{c}] (P{n}.north west) rectangle ([yshift=-{BAR}cm]P{n}.north east);\\end{{scope}}\n"
        for n, c in HEAD.items())
    rep("\n% --- input\n", "\n% header bars\n" + bars + "\n% --- input\n")
    rep("[title, anchor=north west] at ([xshift=0.2cm, yshift=-3pt]P",
        f"[title, anchor=west] at ([xshift=0.22cm, yshift=-{BAR / 2}cm]P", n=5)
    rep("\\node[font=\\small] at ([xshift=-0.27cm, yshift=-0.3cm]P",
        f"\\node[font=\\small, circle, fill=white, inner sep=0.8pt] at ([xshift=-0.45cm, yshift=-{BAR / 2}cm]P", n=3)
    open(DST, "w").write(s)
    print("wrote", DST)


if __name__ == "__main__":
    main()
